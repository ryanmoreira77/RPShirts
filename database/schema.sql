


create table if not exists produtos (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,
  sku          text,
  nome         text,
  team         text not null,
  liga         text,
  temporada    text,
  marca        text,
  modelo       text,
  categoria    text,
  custo        numeric not null default 0,
  preco        numeric not null default 0,
  foto_url     text,
  observacoes  text,
  criado_em    timestamptz not null default now()
);


create table if not exists tamanhos_estoque (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  produto_id  bigint not null references produtos(id) on delete cascade,
  tamanho     text not null check (tamanho in ('PP','P','M','G','XL','2XL','3XL','4XL')),
  qtd         numeric not null default 0,
  unique (produto_id, tamanho)
);


create table if not exists movimentacoes (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null default auth.uid() references auth.users(id) on delete cascade,
  produto_id     bigint not null references produtos(id) on delete cascade,
  tamanho        text not null,
  tipo           text not null check (tipo in ('Entrada','Saída','Venda','Ajuste')),
  quantidade     numeric not null,
  valor_unitario numeric,
  motivo         text,
  observacao     text,
  data           timestamptz not null default now()
);


create table if not exists configuracoes (
  user_id       uuid primary key references auth.users(id) on delete cascade,
  company_name  text default 'Kadu Camisas de Time',
  logo_url      text,
  accent_color  text default '#e11d2e',
  telefone      text,
  endereco      text,
  instagram     text
);


alter table produtos enable row level security;
alter table tamanhos_estoque enable row level security;
alter table movimentacoes enable row level security;
alter table configuracoes enable row level security;

