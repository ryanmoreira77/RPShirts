create or replace function registrar_movimentacao(
  p_produto_id bigint,
  p_tamanho text,
  p_tipo text,
  p_quantidade numeric,
  p_motivo text default '',
  p_observacao text default ''
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_produto produtos%rowtype;
  v_linha tamanhos_estoque%rowtype;
  v_delta numeric;
  v_qtd_atual numeric;
  v_nova_qtd numeric;
  v_valor_unitario numeric;
begin
  select * into v_produto from produtos where id = p_produto_id and user_id = auth.uid();
  if not found then
    return jsonb_build_object('ok', false, 'erro', 'Produto não encontrado.');
  end if;

  if p_tipo = 'Entrada' then
    v_delta := abs(p_quantidade);
  elsif p_tipo in ('Saída', 'Venda') then
    v_delta := -abs(p_quantidade);
  elsif p_tipo = 'Ajuste' then
    v_delta := p_quantidade;
  else
    return jsonb_build_object('ok', false, 'erro', 'Tipo de movimentação inválido.');
  end if;

  select * into v_linha from tamanhos_estoque
    where produto_id = p_produto_id and tamanho = p_tamanho and user_id = auth.uid();

  v_qtd_atual := coalesce(v_linha.qtd, 0);
  v_nova_qtd := v_qtd_atual + v_delta;

  if v_nova_qtd < 0 then
    return jsonb_build_object('ok', false, 'erro',
      'Estoque insuficiente no tamanho ' || p_tamanho || '. Disponível: ' || v_qtd_atual || ' unidade(s).');
  end if;

  if v_linha.id is null then
    insert into tamanhos_estoque (user_id, produto_id, tamanho, qtd)
    values (auth.uid(), p_produto_id, p_tamanho, v_nova_qtd);
  else
    update tamanhos_estoque set qtd = v_nova_qtd where id = v_linha.id;
  end if;

  v_valor_unitario := case when p_tipo = 'Venda' then v_produto.preco else null end;

  insert into movimentacoes (user_id, produto_id, tamanho, tipo, quantidade, motivo, observacao, valor_unitario)
  values (auth.uid(), p_produto_id, p_tamanho, p_tipo, abs(p_quantidade), nullif(p_motivo,''), nullif(p_observacao,''), v_valor_unitario);

  return jsonb_build_object('ok', true, 'novaQtd', v_nova_qtd);
end;
$$;


